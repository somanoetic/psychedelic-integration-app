/**
 * Format a Triggers & Glimmers mapping
 */
function formatTriggersGlimmers(data) {
  const lines = [
    buildHeader('Triggers & Glimmers Map', data.created_at),
  ];

  const triggerGroups = [
    ['sympathetic_triggers', 'Fight / Flight Triggers'],
    ['dorsal_triggers', 'Shutdown Triggers'],
    ['general_triggers', 'General Triggers'],
  ];

  const glimmerGroups = [
    ['sensory_glimmers', 'Sensory Glimmers'],
    ['relational_glimmers', 'Relational Glimmers'],
    ['activity_glimmers', 'Activity Glimmers'],
    ['nature_glimmers', 'Nature Glimmers'],
  ];

  lines.push('TRIGGERS');
  lines.push('');
  triggerGroups.forEach(([key, label]) => {
    const items = data[key];
    if (items?.length) {
      lines.push(`  ${label}:`);
      items.forEach((item) => lines.push(`    - ${item}`));
      lines.push('');
    }
  });

  lines.push('GLIMMERS');
  lines.push('');
  glimmerGroups.forEach(([key, label]) => {
    const items = data[key];
    if (items?.length) {
      lines.push(`  ${label}:`);
      items.forEach((item) => lines.push(`    - ${item}`));
      lines.push('');
    }
  });

  lines.push(buildFooter());
  return lines.join('\n');
}

export async function shareTriggersGlimmers(data) {
  await shareText(formatTriggersGlimmers(data), 'triggers-glimmers');
}

