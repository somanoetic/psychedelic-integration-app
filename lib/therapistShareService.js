/**
 * Share formatted text via the native share sheet.
 *
 * @param {string} text - Formatted summary text
 * @param {string} filename - Filename without extension
 */
async function shareText(text, filename = 'session-summary') {
  const fileUri = `${FileSystem.cacheDirectory}${filename}.txt`;
  await FileSystem.writeAsStringAsync(fileUri, text, {
    encoding: FileSystem.EncodingType.UTF8,
  });

  const canShare = await Sharing.isAvailableAsync();
  if (!canShare) {
    throw new Error('Sharing is not available on this device');
  }

  await Sharing.shareAsync(fileUri, {
    mimeType: 'text/plain',
    dialogTitle: 'Share with Therapist',
    UTI: 'public.plain-text',
  });
}

