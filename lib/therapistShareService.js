import * as FileSystem from 'expo-file-system/legacy';
import * as Sharing from 'expo-sharing';
import { supabase } from './supabase';

const APP_NAME = 'Huxley';
const DIVIDER = '────────────────────────────────────────';

/**
 * Format a date for display
 */
function formatDate(dateStr) {
  if (!dateStr) return 'Unknown date';
  const d = new Date(dateStr);
  return d.toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
  });
}

/**
 * Build the standard header for every share document
 */
function buildHeader(title, date) {
  return [
    `${APP_NAME} — Session Summary`,
    DIVIDER,
    title,
    `Date: ${formatDate(date)}`,
    DIVIDER,
    '',
  ].join('\n');
}

/**
 * Build the standard footer/disclaimer
 */
function buildFooter() {
  return [
    '',
    DIVIDER,
    'This summary was generated by the Huxley integration app.',
    'It reflects the user\'s self-reported experience and AI-guided exploration.',
    'It is not a clinical assessment.',
    DIVIDER,
  ].join('\n');
}

