/**
 * Format a Core Beliefs Assessment
 */
function formatCoreBeliefs(data) {
  const domains = [
    ['value_worthiness', 'Value & Worthiness'],
    ['security_safety', 'Security & Safety'],
    ['performance_competence', 'Performance & Competence'],
    ['control_power', 'Control & Power'],
    ['love_nurturance', 'Love & Nurturance'],
    ['autonomy_independence', 'Autonomy & Independence'],
    ['justice_fairness', 'Justice & Fairness'],
    ['belonging_connection', 'Belonging & Connection'],
    ['others_trust', 'Trust in Others'],
    ['standards_compassion', 'Standards & Self-Compassion'],
  ];

  const scores = domains
    .map(([key, label]) => ({ label, score: data[key] }))
    .filter((d) => d.score != null)
    .sort((a, b) => a.score - b.score);

  const lines = [
    buildHeader('Core Beliefs Assessment', data.created_at),
    'DOMAIN SCORES (0-10 scale, lower = more limiting belief)',
    '',
  ];

  scores.forEach(({ label, score }) => {
    const bar = '█'.repeat(Math.round(score)) + '░'.repeat(10 - Math.round(score));
    lines.push(`  ${bar}  ${score.toFixed(1)}  ${label}`);
  });

  const avg = scores.reduce((s, d) => s + d.score, 0) / scores.length;
  lines.push('');
  lines.push(`Overall average: ${avg.toFixed(1)}/10`);

  if (data.discussion_transcript?.length) {
    lines.push('');
    lines.push('DISCUSSION HIGHLIGHTS');
    lines.push('');
    data.discussion_transcript.forEach((msg) => {
      if (typeof msg === 'string') {
        lines.push(`  ${msg}`);
      } else if (msg.content) {
        const prefix = msg.role === 'user' ? 'User' : 'Huxley';
        lines.push(`  ${prefix}: ${msg.content}`);
      }
    });
  }

  lines.push(buildFooter());
  return lines.join('\n');
}

/**
 * Format a Nervous System Mapping session
 */
function formatNervousSystem(data) {
  const lines = [
    buildHeader('Nervous System Mapping', data.created_at || data.updated_at),
  ];

  const states = [
    ['ventral', 'Ventral Vagal (Safe & Social)'],
    ['sympathetic', 'Sympathetic (Fight/Flight)'],
    ['dorsal', 'Dorsal Vagal (Shutdown/Freeze)'],
  ];

  states.forEach(([key, label]) => {
    const state = data.state_mappings?.[key] || data[key];
    if (!state) return;
    lines.push(label);
    if (state.body_sensations?.length) {
      lines.push(`  Body sensations: ${state.body_sensations.join(', ')}`);
    }
    if (state.emotions?.length) {
      lines.push(`  Emotions: ${state.emotions.join(', ')}`);
    }
    lines.push('');
  });

  if (data.dominant_state) {
    lines.push(`Dominant state: ${data.dominant_state}`);
  }

  lines.push(buildFooter());
  return lines.join('\n');
}

/**
 * Format a Regulating Resources toolkit
 */
function formatRegulatingResources(data) {
  const lines = [
    buildHeader('Regulating Resources Toolkit', data.created_at),
  ];

  const resources = data.state_based_resources || {};

  Object.entries(resources).forEach(([state, categories]) => {
    const stateLabel = {
      sympathetic: 'For Fight/Flight (Sympathetic)',
      dorsal: 'For Shutdown/Freeze (Dorsal)',
      ventral: 'For Maintaining Safety (Ventral)',
    }[state] || state;

    lines.push(stateLabel);
    Object.entries(categories || {}).forEach(([category, items]) => {
      if (items?.length) {
        lines.push(`  ${category}: ${items.join(', ')}`);
      }
    });
    lines.push('');
  });

  lines.push(buildFooter());
  return lines.join('\n');
}

/**
 * Format a Daily Journal entry
 */
function formatJournal(data) {
  const lines = [
    buildHeader('Daily Journal Entry', data.created_at),
  ];

  if (data.title) lines.push(`Title: ${data.title}`);
  if (data.mood) lines.push(`Mood: ${data.mood}`);
  if (data.emotions?.length) lines.push(`Emotions: ${data.emotions.join(', ')}`);
  if (data.themes?.length) lines.push(`Themes: ${data.themes.join(', ')}`);
  lines.push('');

  if (data.raw_text) {
    lines.push('JOURNAL CONTENT');
    lines.push('');
    lines.push(data.raw_text);
    lines.push('');
  }

  if (data.insights) {
    lines.push('INSIGHTS');
    lines.push(data.insights);
    lines.push('');
  }

  if (data.gratitude?.length) {
    lines.push('GRATITUDE');
    data.gratitude.forEach((g) => lines.push(`  - ${g}`));
    lines.push('');
  }

  if (data.challenges?.length) {
    lines.push('CHALLENGES');
    data.challenges.forEach((c) => lines.push(`  - ${c}`));
    lines.push('');
  }

  if (data.goals?.length) {
    lines.push('GOALS');
    data.goals.forEach((g) => lines.push(`  - ${g}`));
  }

  lines.push(buildFooter());
  return lines.join('\n');
}

/**
 * Format a Set Intention session
 */
function formatIntention(data) {
  const lines = [
    buildHeader('Intention Setting', data.created_at),
  ];

  if (data.intention_text) {
    lines.push('INTENTION');
    lines.push(`  "${data.intention_text}"`);
    lines.push('');
  }

  if (data.framework) lines.push(`Framework: ${data.framework}`);
  if (data.session_type) lines.push(`Session type: ${data.session_type}`);

  if (data.ai_conversation_context) {
    const ctx = data.ai_conversation_context;
    if (ctx.frameworks_explored?.length) {
      lines.push(`Frameworks explored: ${ctx.frameworks_explored.join(', ')}`);
    }
  }

  lines.push(buildFooter());
  return lines.join('\n');
}

/**
 * Format an IFS Parts Work session
 */
function formatIFSParts(parts) {
  const lines = [
    buildHeader('IFS Parts Inventory', new Date().toISOString()),
  ];

  if (!parts?.length) {
    lines.push('No parts have been identified yet.');
    lines.push(buildFooter());
    return lines.join('\n');
  }

  parts.forEach((part, i) => {
    lines.push(`${i + 1}. ${part.part_name || 'Unnamed Part'}`);
    if (part.part_role) lines.push(`   Role: ${part.part_role}`);
    if (part.part_feelings) lines.push(`   Feelings: ${part.part_feelings}`);
    if (part.protective_strategy) lines.push(`   Strategy: ${part.protective_strategy}`);
    if (part.location_in_body) lines.push(`   Body location: ${part.location_in_body}`);
    if (part.original_wound_description) lines.push(`   Wound: ${part.original_wound_description}`);
    lines.push('');
  });

  lines.push(buildFooter());
  return lines.join('\n');
}

/**
 * Format an Experience Mapping session (conversation)
 */
function formatExperienceMapping(data) {
  const sessionData = data.session_data || data;
  const lines = [
    buildHeader('Experience Processing Session', data.created_at),
  ];

  if (sessionData.sessionType) lines.push(`Type: ${sessionData.sessionType}`);
  lines.push('');

  const messages = sessionData.messages || [];
  if (messages.length) {
    lines.push('CONVERSATION');
    lines.push('');
    messages.forEach((msg) => {
      const role = msg.role === 'user' ? 'User' : 'Huxley';
      lines.push(`${role}:`);
      lines.push(`  ${msg.content}`);
      lines.push('');
    });
  }

  lines.push(buildFooter());
  return lines.join('\n');
}

/**
 * Format a guided exercise completion
 */
function formatExercise(exercise) {
  const lines = [
    buildHeader('Guided Exercise Completed', new Date().toISOString()),
  ];

  lines.push(`Exercise: ${exercise.title || exercise.name}`);
  if (exercise.category) lines.push(`Category: ${exercise.category}`);
  if (exercise.duration) lines.push(`Duration: ${exercise.duration}`);
  if (exercise.description) lines.push(`Description: ${exercise.description}`);
  lines.push('');

  if (exercise.steps?.length) {
    lines.push('STEPS COMPLETED');
    exercise.steps.forEach((step, i) => {
      const text = typeof step === 'string' ? step : step.instruction || step.text;
      lines.push(`  ${i + 1}. ${text}`);
    });
  }

  lines.push(buildFooter());
  return lines.join('\n');
}

