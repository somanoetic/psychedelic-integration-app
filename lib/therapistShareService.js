// FORMAT ALL — combines multiple modules into one document
// ═══════════════════════════════════════════════════════════════

async function formatAll(userId) {
  const sections = [];

  sections.push(`${APP_NAME} — Complete Integration Summary`);
  sections.push(DIVIDER);
  sections.push(`Generated: ${formatDate(new Date().toISOString())}`);
  sections.push(DIVIDER);
  sections.push('');

  // Core Beliefs
  const { data: beliefs } = await supabase
    .from('core_beliefs_assessments')
    .select('*')
    .eq('user_id', userId)
    .order('created_at', { ascending: false })
    .limit(1)
    .single();

  if (beliefs) {
    sections.push('=== CORE BELIEFS ===');
    sections.push(formatCoreBeliefs(beliefs));
    sections.push('');
  }

  // Nervous System
  const { data: nsData } = await supabase
    .from('polyvagal_patterns')
    .select('*')
    .eq('user_id', userId)
    .order('updated_at', { ascending: false })
    .limit(1)
    .single();

  if (nsData) {
    sections.push('=== NERVOUS SYSTEM MAP ===');
    sections.push(formatNervousSystem(nsData));
    sections.push('');
  }

  // Regulating Resources
  const { data: resources } = await supabase
    .from('regulating_resources')
    .select('*')
    .eq('user_id', userId)
    .order('created_at', { ascending: false })
    .limit(1)
    .single();

  if (resources) {
    sections.push('=== REGULATING RESOURCES ===');
    sections.push(formatRegulatingResources(resources));
    sections.push('');
  }

  // IFS Parts
  const { data: parts } = await supabase
    .from('ifs_parts_inventory')
    .select('*')
    .eq('user_id', userId);

  if (parts?.length) {
    sections.push('=== IFS PARTS INVENTORY ===');
    sections.push(formatIFSParts(parts));
    sections.push('');
  }

  // Recent Intentions
  const { data: intentions } = await supabase
    .from('session_intentions')
    .select('*')
    .eq('user_id', userId)
    .order('created_at', { ascending: false })
    .limit(3);

  if (intentions?.length) {
    sections.push('=== RECENT INTENTIONS ===');
    intentions.forEach((int) => {
      sections.push(formatIntention(int));
    });
    sections.push('');
  }

  // Recent Journals
  const { data: journals } = await supabase
    .from('daily_journals')
    .select('*')
    .eq('user_id', userId)
    .order('created_at', { ascending: false })
    .limit(5);

  if (journals?.length) {
    sections.push('=== RECENT JOURNAL ENTRIES ===');
    journals.forEach((j) => {
      sections.push(formatJournal(j));
    });
  }

  return sections.join('\n');
}

